"""THIRD_PARTY_NOTICES.txt: the license and copyright notices of the third-party software we ship.

What ships, and so what is listed:
- the Python packages installed in the Docker image: every package pinned in
  requirements-lock.txt and requirements-docker.txt;
- the npm packages bundled into the control panel: the non-development entries of
  frontend/package-lock.json.

The notices are the packages' own files (LICENSE, COPYING, NOTICE…), read from the installed
copies, so they always match the exact versions in use. A package that ships no license file
needs one in docker/notices/<name>-<version>.txt, taken from its official source.

    python docker/third_party_notices.py           check that the file is up to date (CI, tests)
    python docker/third_party_notices.py --write   rewrite it after changing dependencies
    python docker/third_party_notices.py --check --python-only
        inside the Docker image (no node_modules there): check the Python notices against the
        installed packages, and that the panel's list matches frontend/package-lock.json

It needs the installed packages: `pip install -r requirements-dev.txt` and `npm ci` in
frontend/. Standard library only; the output is the same on every operating system.
"""
import argparse
import json
import re
import sys
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "THIRD_PARTY_NOTICES.txt"
OVERRIDES = ROOT / "docker" / "notices"
FRONTEND = ROOT / "frontend"
NOTICE_FILE = re.compile(r"^(licen[cs]e|copying|notice)([._-].*)?$", re.IGNORECASE)
RULE = "=" * 78
NPM_HEADING = "PART 2. CONTROL PANEL (npm packages bundled into the web page)"

HEADER = """THIRD-PARTY SOFTWARE NOTICES
Bluesky -> Discord Alert Bot

This project is licensed under the MIT License (see LICENSE). Its Docker image and its
control panel also contain the third-party software listed below, which keeps its own
license. The original license and copyright notices of each package follow, as shipped
with the exact version in use.

This file is generated by docker/third_party_notices.py. Don't edit it by hand.

Not repeated here:
- The Docker image's base system: Debian packages and Python itself, from the official
  python:3.11-slim image. Their notices are inside the image, in /usr/share/doc/*/copyright
  and /usr/local/lib/python3.11/LICENSE.txt; Debian's sources are at
  https://sources.debian.org. The base image's own pip, setuptools and wheel keep their
  notices in their *.dist-info folders.
- Compiled code inside some Python packages (for example OpenSSL in cryptography, and Rust
  libraries in pydantic-core and libipld) is covered by those packages' notices below, as
  their authors ship them.
- Development and test tools, which are never distributed.

The control panel's icon (favicon.svg) is based on the "send" icon from Lucide/Feather;
see lucide-react below.
"""


class NoticeError(Exception):
    pass


def _text(data: bytes) -> str:
    try:
        text = data.decode("utf-8-sig")
    except UnicodeDecodeError:
        text = data.decode("latin-1")
    lines = [line.rstrip() for line in text.replace("\r\n", "\n").replace("\r", "\n").split("\n")]
    while lines and not lines[-1]:
        lines.pop()
    while lines and not lines[0]:
        lines.pop(0)
    return "\n".join(lines)


def _entry(name, version, license_name, sources):
    out = [RULE, f"{name} {version}", f"License: {license_name or 'see below'}", RULE]
    for label, text in sources:
        out += ["", f"--- {label} ---", "", text]
    return "\n".join(out)


# -- Python ----------------------------------------------------------------------------------------
def pinned_python_packages():
    """{name: version} from requirements-docker.txt and the files it includes."""
    pins, seen = {}, set()

    def read(path):
        if path in seen:
            return
        seen.add(path)
        for raw in path.read_text(encoding="utf-8").splitlines():
            line = raw.split("#", 1)[0].strip()
            if line.startswith("-r "):
                read(path.parent / line[3:].strip())
            elif "==" in line:
                name, version = line.split("==", 1)
                pins[name.strip()] = version.strip()
            elif line:
                raise NoticeError(f"{path.name}: not an exact pin: {raw!r}")

    read(ROOT / "requirements-docker.txt")
    return pins


def _python_license(dist):
    meta = dist.metadata
    if meta.get("License-Expression"):
        return meta["License-Expression"]
    classifiers = [c.split("::")[-1].strip() for c in meta.get_all("Classifier") or [] if c.startswith("License ::")]
    if classifiers:
        return ", ".join(classifiers)
    first = (meta.get("License") or "").strip().splitlines()
    return first[0][:60] if first else ""


def python_entries():
    entries = []
    for name, version in sorted(pinned_python_packages().items(), key=lambda kv: kv[0].lower()):
        try:
            dist = metadata.distribution(name)
        except metadata.PackageNotFoundError:
            raise NoticeError(f"{name} {version} isn't installed. Install the image's packages first: "
                              "pip install -r requirements-dev.txt") from None
        if dist.version != version:
            raise NoticeError(f"{name}: {dist.version} is installed, but the lock file says {version}. "
                              "Install the exact versions: pip install -r requirements-dev.txt")
        files = sorted((f for f in dist.files or [] if NOTICE_FILE.match(Path(str(f)).name)),
                       key=lambda f: (str(f).count("/"), str(f).lower()))
        sources = [(str(f).replace("\\", "/"), _text(Path(dist.locate_file(f)).read_bytes())) for f in files]
        override = OVERRIDES / f"{dist.metadata['Name']}-{version}.txt"
        if not sources and override.is_file():
            sources = [(f"docker/notices/{override.name}", _text(override.read_bytes()))]
        if not sources:
            raise NoticeError(f"{name} {version} ships no license file. Add its license, from its official "
                              f"source for this version, as docker/notices/{override.name}")
        entries.append(_entry(dist.metadata["Name"], version, _python_license(dist), sources))
    return entries


# -- npm -------------------------------------------------------------------------------------------
def bundled_npm_packages():
    """[(lock path, name, version, license)] for everything the panel ships (not dev tools)."""
    lock = json.loads((FRONTEND / "package-lock.json").read_text(encoding="utf-8"))["packages"]
    out = []
    for path, info in lock.items():
        if not path or info.get("dev") or info.get("optional") or info.get("link"):
            continue
        name = path.rsplit("node_modules/", 1)[-1]
        out.append((path, name, info["version"], info.get("license", "")))
    return sorted(out, key=lambda p: (p[1].lower(), p[2]))


def npm_entries():
    entries = []
    for path, name, version, license_name in bundled_npm_packages():
        folder = FRONTEND / path
        try:
            installed = json.loads((folder / "package.json").read_text(encoding="utf-8"))["version"]
        except FileNotFoundError:
            raise NoticeError(f"{name} isn't installed. Run: cd frontend && npm ci") from None
        if installed != version:
            raise NoticeError(f"{name}: {installed} is installed, but package-lock.json says {version}. "
                              "Run: cd frontend && npm ci")
        files = sorted((f for f in folder.iterdir() if f.is_file() and NOTICE_FILE.match(f.name)),
                       key=lambda f: f.name.lower())
        if not files:
            raise NoticeError(f"{name} {version} ships no license file; it needs a notice before it can ship")
        entries.append(_entry(name, version, license_name, [(f.name, _text(f.read_bytes())) for f in files]))
    return entries


# -- the file --------------------------------------------------------------------------------------
def _contents(python, npm):
    def heading(entry):
        lines = entry.split("\n")
        return f"  {lines[1]} ({lines[2].removeprefix('License: ')})"

    parts = [HEADER, "CONTENTS", "", "PART 1. DOCKER IMAGE (Python packages)"]
    parts += [heading(e) for e in python]
    parts += ["", NPM_HEADING]
    parts += [heading(e) for e in npm]
    parts += ["", "", "PART 1. DOCKER IMAGE (Python packages)", "", "\n\n".join(python),
              "", "", NPM_HEADING, "", "\n\n".join(npm)]
    return "\n".join(parts) + "\n"


def build():
    return _contents(python_entries(), npm_entries())


def check_python_only(current: str):
    """For the Docker image: the Python notices are exact, and the panel's list is current."""
    expected = python_entries()
    for entry in expected:
        if entry not in current:
            raise NoticeError(f"the notice for {entry.split(chr(10))[1]} is missing or out of date")
    listed = re.findall(r"^  (.+) \(", current.split(NPM_HEADING, 1)[1].split("\n\n\n", 1)[0], re.MULTILINE)
    wanted = [f"{name} {version}" for _, name, version, _ in bundled_npm_packages()]
    if listed != wanted:
        raise NoticeError("the control panel's packages don't match frontend/package-lock.json")
    python_listed = re.findall(r"^  (.+) \(", current.split(NPM_HEADING, 1)[0], re.MULTILINE)
    if len(python_listed) != len(expected):
        raise NoticeError("the file lists Python packages that aren't installed")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--write", action="store_true", help="rewrite THIRD_PARTY_NOTICES.txt")
    parser.add_argument("--check", action="store_true", help="only check (the default)")
    parser.add_argument("--python-only", action="store_true", help="in the Docker image: no node_modules there")
    args = parser.parse_args(argv)
    fix = "Run: python docker/third_party_notices.py --write (with the exact packages installed), and commit it."
    try:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.is_file() else ""
        if args.python_only:
            check_python_only(current)
            print("THIRD_PARTY_NOTICES.txt matches the installed Python packages and the panel's lock file.")
            return 0
        text = build()
        if args.write:
            OUTPUT.write_text(text, encoding="utf-8", newline="\n")
            print(f"Wrote {OUTPUT.name}.")
            return 0
        if current != text:
            raise NoticeError("THIRD_PARTY_NOTICES.txt is out of date: the dependencies changed. " + fix)
    except NoticeError as exc:
        print(f"THIRD_PARTY_NOTICES: {exc}", file=sys.stderr)
        return 1
    print("THIRD_PARTY_NOTICES.txt is up to date.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
